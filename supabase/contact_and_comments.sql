-- Contact form inbox + comment fixes.
-- Run once in Supabase Dashboard -> SQL Editor. Safe to re-run.

-- ========================================
-- TABLE: messages (contact form inbox)
-- ========================================
-- Written only by the /api/contact server route (service role key);
-- read and managed by the logged-in admin at /admin/messages.

CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    email text NOT NULL CHECK (char_length(email) BETWEEN 3 AND 254),
    message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 3000),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at DESC);

ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- No policies for anon: visitors can never read or write messages directly.
DROP POLICY IF EXISTS "Admin read messages" ON public.messages;
CREATE POLICY "Admin read messages" ON public.messages
FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Admin update messages" ON public.messages;
CREATE POLICY "Admin update messages" ON public.messages
FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin delete messages" ON public.messages;
CREATE POLICY "Admin delete messages" ON public.messages
FOR DELETE TO authenticated USING (true);

-- Live updates in the admin inbox
DO $$
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- ========================================
-- COMMENTS: likes that actually save
-- ========================================
-- Visitors may add exactly one like at a time, without being able to edit
-- anything else on a comment.

CREATE OR REPLACE FUNCTION public.increment_comment_likes(comment_id bigint)
RETURNS integer
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    UPDATE public.comments
    SET likes = COALESCE(likes, 0) + 1
    WHERE id = comment_id
    RETURNING likes;
$$;

REVOKE ALL ON FUNCTION public.increment_comment_likes(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.increment_comment_likes(bigint) TO anon, authenticated;

-- ========================================
-- COMMENTS: length limits (match the site's form limits)
-- ========================================

DO $$
BEGIN
    ALTER TABLE public.comments
        ADD CONSTRAINT comments_name_length CHECK (char_length(name) BETWEEN 1 AND 60) NOT VALID;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    ALTER TABLE public.comments
        ADD CONSTRAINT comments_comment_length CHECK (char_length(comment) BETWEEN 1 AND 1000) NOT VALID;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- ========================================
-- STORAGE: comment images (max 5 MB, images only)
-- ========================================

UPDATE storage.buckets
SET file_size_limit = 5242880,
    allowed_mime_types = ARRAY['image/png', 'image/jpeg', 'image/gif', 'image/webp']
WHERE id = 'comments';
